-- 004: 日线序列缓存的抓取记录
--
-- 背景：行情源（腾讯 / 新浪）都只支持「最近 N 根」，不支持按日期区间查询，
-- 因此每次查一个历史交易日都要把全市场 5600+ 只股票重抓一遍（约 13s）。
-- 但实测「多取几根几乎不要钱」：新浪单请求延迟 20 根 241ms → 120 根 242ms，
-- 端到端冷启动 20 根 vs 62 根交替三轮中位 14362ms vs 12389ms，无差异。
-- 于是把策略从「刚好抓够目标日那几根」改成「固定抓一个半年窗口、整条序列落库」，
-- 窗口内的其它日期之后都是 0 请求。
--
-- 本表记录「每只股票的序列是哪天抓的、覆盖到哪一天」，用于判断某个目标日期
-- 能否直接查 `daily_bar_cache` 而不必重新请求。

CREATE TABLE IF NOT EXISTS kline_series_meta (
    stock_code TEXT PRIMARY KEY,
    -- 抓取日期（本地时区 YYYY-MM-DD）。同一天不再重抓，见下 `complete` 的说明
    fetched_at TEXT NOT NULL,
    -- 本次落库的最早交易日。目标日早于它意味着序列没覆盖到
    first_date TEXT NOT NULL,
    -- 本次落库的最晚交易日，正常就是最近一个交易日
    last_date TEXT NOT NULL,
    -- 1 = 已回溯到上市首日（返回根数 < 请求根数，说明上游没更多数据了）；
    -- 0 = 被请求窗口截断。只有 1 时，「目标日早于 first_date」才能判定为
    -- 「那天还没上市」而不是「窗口不够长，得加大窗口重抓」
    complete INTEGER NOT NULL
);
